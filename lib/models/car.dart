class Car {
  final String brand;
  final String model;
  final int year;
  final int mileage;
  final String fuel;
  final String engine;
  final String registration;

  const Car({
    required this.brand,
    required this.model,
    required this.year,
    required this.mileage,
    required this.fuel,
    required this.engine,
    required this.registration,
  });
}